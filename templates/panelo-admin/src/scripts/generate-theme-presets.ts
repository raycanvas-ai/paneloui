/**
 * Rebuilds src/lib/preferences/presets.ts from the CSS files in src/styles/presets.
 *
 * Each preset file starts with a `@preset <Name>` comment and scopes its tokens to
 * html[data-theme-preset="<id>"] (light) and html.dark[data-theme-preset="<id>"] (dark).
 * The generated list carries each preset's primary colour so pickers can draw a swatch.
 *
 *   npm run generate:presets
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const src = join(__dirname, "..");
const presetDir = join(src, "styles/presets");
const target = join(src, "lib/preferences/presets.ts");

type Preset = { id: string; name: string; light: string; dark: string };

/** First `--primary` inside the block whose selector matches. */
function primaryIn(css: string, selector: RegExp): string {
  const block = css.match(new RegExp(`${selector.source}\\s*\\{([^}]*)\\}`));
  const value = block?.[1].match(/--primary:\s*([^;]+);/)?.[1].trim();
  if (!value) throw new Error(`No --primary found for ${selector}`);
  return value;
}

const globals = readFileSync(join(src, "app/globals.css"), "utf8");
const presets: Preset[] = [
  {
    id: "default",
    name: "Panelo",
    light: primaryIn(globals, /:root/),
    dark: primaryIn(globals, /\.dark/),
  },
];

for (const file of readdirSync(presetDir)
  .filter((name) => name.endsWith(".css"))
  .sort()) {
  const css = readFileSync(join(presetDir, file), "utf8");
  const id = css.match(/data-theme-preset="([^"]+)"/)?.[1];
  const name = css.match(/@preset\s+([^\s—*]+)/)?.[1];
  if (!id || !name) throw new Error(`${file} needs a "@preset Name" comment and a data-theme-preset selector`);

  const scope = `html\\[data-theme-preset="${id}"\\]`;
  const darkScope = `html\\.dark\\[data-theme-preset="${id}"\\]`;
  presets.push({ id, name, light: primaryIn(css, new RegExp(scope)), dark: primaryIn(css, new RegExp(darkScope)) });
}

const entries = presets
  .map((p) => `  { id: "${p.id}", name: "${p.name}", swatch: { light: "${p.light}", dark: "${p.dark}" } },`)
  .join("\n");

writeFileSync(
  target,
  `// Generated by \`npm run generate:presets\` from src/styles/presets/*.css. Do not edit by hand.

export const PRESETS = [
${entries}
] as const;

export const PRESET_IDS = PRESETS.map((preset) => preset.id);

export type PresetId = (typeof PRESETS)[number]["id"];
`,
);

console.log(`presets.ts: ${presets.map((p) => p.id).join(", ")}`);
