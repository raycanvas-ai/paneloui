import { rootUser } from "@/data/users";

export type Conversation = {
  id: number;
  group: "Pinned" | "Today" | "Yesterday";
  name: string;
  subject: string;
  preview: string;
  time: string;
  isUnread: boolean;
  isOnline: boolean;
  unreadCount: number;
  contact: Contact;
  messages: Message[];
};

export type Message = {
  id: number;
  align: "start" | "end";
  text: string;
  time: string;
  reaction?: string;
};

export type Contact = {
  name: string;
  role: string;
  company: string;
  email: string;
  phone: string;
  website: string;
  location: string;
  timezone: string;
  status: string;
  qualifiedAt: string;
  tags: string[];
};

/** The agent replying in every thread is the signed-in workspace owner. */
export const currentUser = { name: rootUser.name, email: rootUser.email };

type Line = [align: Message["align"], text: string, time: string, reaction?: string];

/** Message ids are derived from the conversation id so they stay unique across threads. */
function thread(conversationId: number, lines: Line[]): Message[] {
  return lines.map(([align, text, time, reaction], index) => ({
    id: conversationId * 100 + index,
    align,
    text,
    time,
    ...(reaction ? { reaction } : {}),
  }));
}

